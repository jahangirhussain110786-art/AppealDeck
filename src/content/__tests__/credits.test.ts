import { existsSync, readFileSync, readdirSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { CREDITS, MARQUEE, MARQUEE_NAMES, SERVICES, SERVICE_NAMES } from "@/content/credits";
import { shouldDrift } from "@/lib/creditsMotion";

const ROOT = process.cwd();
const read = (file: string) => readFileSync(path.join(ROOT, file), "utf8");
const GLYPH_DIR = path.join(ROOT, "public", "credits");

const GLYPHS = MARQUEE.flatMap((entry) => (entry.logo ? [entry.logo] : []));

describe("credits", () => {
  it("thanks every service the privacy policy discloses, in the row and nowhere else", () => {
    const legal = read("src/content/legal.ts");
    for (const service of SERVICES) {
      expect(legal, `${service} is credited but not disclosed in legal.ts`).toContain(service);
      expect(MARQUEE_NAMES, `${service} is disclosed but missing from the row`).toContain(service);
    }
    expect(SERVICES).toEqual(SERVICE_NAMES.map((entry) => entry.name));
  });

  it("keeps the row long enough to loop without a gap, and no name twice", () => {
    expect(MARQUEE_NAMES.length).toBeGreaterThanOrEqual(12);
    expect(MARQUEE_NAMES.length).toBeLessThanOrEqual(24);
    expect(new Set(MARQUEE_NAMES).size).toBe(MARQUEE_NAMES.length);
  });

  // 27 Oct 2026: the founder asked for the acknowledgment and nothing else. An expanded list with
  // roles is a description of our vendors on a public page, which is more than thanks and more than
  // the privacy policy needs (it keeps its own account of what each service receives).
  it("carries no expanded list or role description", () => {
    expect(read("src/content/credits.ts")).not.toMatch(/\brole\s*:/);
    expect(read("src/components/marketing/ThanksBand.tsx")).not.toContain("<details");
  });

  it("shows only glyphs we vendored, each from the generated set", () => {
    const files = readdirSync(GLYPH_DIR).sort();
    expect(files.length).toBeGreaterThan(0);
    expect(files).toEqual(GLYPHS.map((logo) => path.basename(logo)).sort());
    for (const logo of GLYPHS) {
      const file = path.join(ROOT, "public", logo.replace(/^\//, ""));
      expect(existsSync(file), `${logo} is referenced but missing`).toBe(true);
      const svg = readFileSync(file, "utf8");
      // Generated by scripts/build-credit-logos.mjs: a provenance line, one path, white fill.
      expect(svg).toContain("simple-icons");
      expect(svg).toContain('fill="#ffffff"');
      expect(svg.match(/<path /g)?.length).toBe(1);
    }
  });

  it("sets the three names the founder chose in a substitute typeface", () => {
    const face = (name: string) => MARQUEE.find((entry) => entry.name === name)?.face;
    expect(face("Claude")).toBe("serif");
    expect(face("ChatGPT")).toBe("grotesque");
    expect(face("Microsoft")).toBe("humanist");
    for (const entry of MARQUEE) {
      if (entry.face) expect(["serif", "grotesque", "humanist"]).toContain(entry.face);
    }
  });

  // The words that turn a credit into a relationship claim. Google's, Anthropic's and OpenAI's
  // brand rules all single these out, and the site's own footer already denies any affiliation.
  it("makes no relationship claim", () => {
    const claim =
      /\b(partner|partnership|sponsor|sponsorship|endorse|endorsement|affiliate|affiliation|certified|official|co-engineer)/i;
    expect(claim.test(CREDITS.heading)).toBe(false);
    expect(claim.test(CREDITS.line)).toBe(false);
    for (const name of MARQUEE_NAMES) expect(claim.test(name), name).toBe(false);
  });

  it("denies a relationship once, in the disclaimer", () => {
    expect(CREDITS.disclaimer).toContain("No partnership, sponsorship or endorsement");
    expect(CREDITS.heading).toBe("With thanks to:");
  });

  it("has the motion exception recorded in the UI spec", () => {
    const spec = read("Planning/03-PHASE-2-BUILD/06-PREMIUM-UI-UX-SPEC.md");
    expect(spec).toContain("home-page credits row");
  });
});

describe("shouldDrift", () => {
  const still = { visible: false, documentHidden: false, paused: false };
  const moving = { visible: true, documentHidden: false, paused: false };

  it("moves while on screen, in a visible tab, unpaused", () => {
    expect(shouldDrift(moving)).toBe(true);
  });

  it("stays still on every other input", () => {
    const stops: [string, typeof moving][] = [
      ["off screen", { ...moving, visible: false }],
      ["tab in the background", { ...moving, documentHidden: true }],
      ["the reader pressed pause", { ...moving, paused: true }],
    ];
    for (const [label, state] of stops) {
      expect(shouldDrift(state), label).toBe(false);
    }
    expect(shouldDrift(still)).toBe(false);
  });

  // 27 Oct 2026: the founder's Windows reports animations off, which Chrome maps to
  // prefers-reduced-motion — and every strip he compared us with moves anyway. So the OS animation
  // setting is not an input to the row; only the pointer is. This keeps it that way.
  it("ignores the OS animation setting — no reduced-motion branch in the component", () => {
    const component = read("src/components/marketing/CreditsMarquee.tsx");
    expect(component).not.toContain("prefers-reduced-motion");
    expect(component).not.toContain("useSyncExternalStore");
    expect(component).not.toContain("data-motion");
  });

  // 27 Oct 2026, founder: the pause button is gone. The pointer is the pause — hovering the row (or
  // tabbing to it) holds it still, moving away continues it. A button must not creep back.
  it("has no pause button; the pointer holds the row instead", () => {
    const component = read("src/components/marketing/CreditsMarquee.tsx");
    expect(component).not.toContain("<button");
    expect(component).toContain("onMouseEnter");
    expect(component).toContain("onMouseLeave");
  });
});
